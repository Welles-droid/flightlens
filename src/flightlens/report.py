"""Render a Verdict as a rich table, JSON, or a shareable Markdown report."""

from __future__ import annotations

import json
import os
from pathlib import Path

from rich.console import Console
from rich.table import Table

from flightlens import __version__
from flightlens.verdict import AxisVerdict, Verdict

_GRADE_STYLE = {"well_tuned": "green", "needs_attention": "yellow", "poorly_tuned": "red"}


def _fmt(value, spec: str, unit: str = "") -> str:
    return "—" if value is None else f"{value:{spec}}{unit}"


def _axis_rows(a: AxisVerdict) -> list[tuple[str, str]]:
    t, o = a.tracking, a.oscillation
    if o.insufficient_data:
        osc = "insufficient data"
    elif o.oscillating:
        osc = f"{o.severity} @ {o.frequency_hz:.1f} Hz (~{o.amplitude:.1f} deg/s)"
    else:
        osc = "none"
    return [
        ("Grade", a.grade),
        ("Oscillation", osc),
        ("Mean tracking error", _fmt(t.mean_abs_deg, ".2f", "°")),
        ("P95 tracking error", _fmt(t.p95_abs_deg, ".2f", "°")),
        ("Max tracking error", _fmt(t.max_abs_deg, ".2f", "°")),
        (f"Time above {t.threshold_deg:.0f}°", f"{t.time_above_threshold_frac:.1%}"),
        ("Mean rate error", _fmt(t.rate_mean_abs_dps, ".1f", " deg/s")),
    ]


def render_json(verdict: Verdict) -> str:
    return json.dumps(verdict.to_dict(), indent=2)


def render_table(verdict: Verdict, console: Console) -> None:
    for a in verdict.axes:
        table = Table(title=a.axis.capitalize(), title_justify="left", show_header=False)
        table.add_column("Metric", style="bold")
        table.add_column("Value")
        for label, value in _axis_rows(a):
            style = _GRADE_STYLE.get(value) if label == "Grade" else None
            table.add_row(label, value, style=style)
        console.print(table)
    if verdict.vibration["available"]:
        console.print(f"Vibration: {verdict.vibration['overall']}")
    style = _GRADE_STYLE[verdict.overall_grade]
    console.print(f"\n[bold {style}]{verdict.overall_grade}[/]: {verdict.one_liner}")
    if verdict.recommendations:
        console.print("\n[bold]Recommendations[/]")
        for r in verdict.recommendations:
            console.print(f"  • {r}", highlight=False)


def render_markdown(verdict: Verdict, log_path: str | os.PathLike) -> str:
    log_path = Path(log_path)
    lines = [
        f"# FlightLens report: {log_path.name}",
        "",
        f"**Verdict: `{verdict.overall_grade}`** — {verdict.one_liner}",
        "",
        "## Log",
        "",
        f"- File: `{log_path.name}`",
    ]
    if log_path.exists():
        lines.append(f"- Size: {log_path.stat().st_size / 1024:.0f} KiB")
    lines += [
        f"- Duration analysed: {verdict.stats['duration_s']:.1f} s",
        f"- Axes analysed: {', '.join(verdict.stats['axes_analyzed'])}",
        f"- Messages: {', '.join(f'{k} ({v})' for k, v in verdict.stats['messages'].items())}",
        "",
    ]
    for a in verdict.axes:
        lines += [f"## {a.axis.capitalize()}", "", "| Metric | Value |", "| --- | --- |"]
        lines += [f"| {label} | {value} |" for label, value in _axis_rows(a)]
        lines.append("")
    vibe = verdict.vibration
    lines += ["## Vibration", ""]
    if vibe["available"]:
        lines.append(f"Overall: **{vibe['overall']}**")
        lines.append("")
        lines += [
            f"- {name}: mean {v['mean']:.1f}, max {v['max']:.1f} m/s/s ({v['grade']})"
            for name, v in vibe["axes"].items()
        ]
    else:
        lines.append("No VIBE data in log.")
    lines += ["", "## Recommendations", ""]
    lines += [f"- {r}" for r in verdict.recommendations] or ["- None — keep flying."]
    lines += ["", f"_Generated by FlightLens {__version__}._", ""]
    return "\n".join(lines)
